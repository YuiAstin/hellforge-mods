static int WeaponSoundIndex(uint64_t res)
{
    for (int i = 0; i < (int)(sizeof kWeaponSound / sizeof kWeaponSound[0]); i++) if (kWeaponSound[i].res == res) return i;
    return -1;
}
/* the shots made lately, for the HUD side: x, y, z, the sound (an index), sequence */
#define SHOT_SOUNDS 64
static float g_shotSnd[SHOT_SOUNDS][5];
static volatile unsigned g_shotSndSeq;
static __attribute__((unused)) void ShotSound(uint64_t res, const float at[3])
{
    int i = WeaponSoundIndex(res);
    if (i < 0) return;
    unsigned q = g_shotSndSeq + 1;
    float* r = g_shotSnd[q % SHOT_SOUNDS];
    r[0] = at[0]; r[1] = at[1]; r[2] = at[2]; r[3] = (float)i; r[4] = (float)q;
    g_shotSndSeq = q;
}
static int ShotSounds(unsigned after, float* out, int max)
{
    unsigned last = g_shotSndSeq, first = after + 1;
    if (last - after > SHOT_SOUNDS) first = last - SHOT_SOUNDS + 1;
    int n = 0;
    for (unsigned q = first; q != last + 1 && n < max; q++)
    {
        const float* r = g_shotSnd[q % SHOT_SOUNDS];
        if ((unsigned)r[4] != q) continue;
        memcpy(out + 5 * n, r, 20);
        n++;
    }
    return n;
}
