"""Generate the Extra Boosters patch tables from the dump and the reviewed note.

sites:  every instruction encoding a BoosterSettings address (chain_sweep's 117), with the displacement's offset in the
        instruction and the table offset it addresses.
bounds: every instruction the note classifies as a booster guard / loop end / sentinel / clamp (112), with the offset
        and width of the byte(s) holding the count, and its value (0x15, or 0x13 for idx-1).
names:  the two readers of the enum name list at 0x21DD630.
"""
import json, re, sys
import capstone as cs
from capstone import x86

DUMP, NOTE, SWEEP, OUT = sys.argv[1:5]
d = open(DUMP, 'rb').read()
md = cs.Cs(cs.CS_ARCH_X86, cs.CS_MODE_64)
md.detail = True
TABLE, ROW, N = 0x32FDA90, 56, 21
NAMES = 0x21DD630


def ins_at(a):
    i = next(md.disasm(d[a:a + 16], a), None)
    assert i is not None and i.address == a, hex(a)
    return i


# ---- sites
S = json.load(open(SWEEP))
sites = []
for a, kind, off, text, root in sorted(S['sites']):
    i = ins_at(a)
    assert i.disp_offset and i.disp_size == 4, (hex(a), text)
    disp = int.from_bytes(d[a + i.disp_offset:a + i.disp_offset + 4], 'little', signed=True)
    if kind == 'rip':
        assert a + i.size + disp == TABLE + off, hex(a)
    else:
        assert disp == TABLE + off, hex(a)
    sites.append((a, i.disp_offset, i.size, 1 if kind == 'rip' else 0, off))

# ---- bounds, from the note's classified tables
note = open(NOTE).read().splitlines()
b0 = next(k for k, l in enumerate(note) if l.startswith('### b.'))
c0 = next(k for k, l in enumerate(note) if l.startswith('### c.'))
cls = None
bounds = []
for l in note[b0:c0]:
    m = re.match(r'\*\*(Guards|Loop ends|Sentinels|Clamp|NOT booster)', l)
    if m:
        cls = m.group(1)
        continue
    if l.startswith('**'):
        cls = None
    m = re.match(r'\|\s*`0x([0-9A-Fa-f]+)`\s*\|\s*`([^`]+)`', l)
    if not m or cls in (None, 'NOT booster'):
        continue
    a = int(m.group(1), 16)
    i = ins_at(a)
    # the operand holding the count: an immediate, or (lea) a displacement
    at = width = value = None
    for o in i.operands:
        if o.type == x86.X86_OP_IMM and o.imm in (0x13, 0x15):
            at, width, value = i.imm_offset, i.imm_size, o.imm
        elif o.type == x86.X86_OP_MEM and i.mnemonic == 'lea' and o.mem.disp in (0x13, 0x15):
            at, width, value = i.disp_offset, i.disp_size, o.mem.disp
    assert at is not None, (hex(a), i.mnemonic, i.op_str)
    raw = int.from_bytes(d[a + at:a + at + width], 'little')
    assert raw == value, (hex(a), raw, value)
    bounds.append((a, at, width, value, cls))

# ---- name readers
names = []
for a in (0x14E7214, 0x14FDB5D):
    i = ins_at(a)
    disp = int.from_bytes(d[a + i.disp_offset:a + i.disp_offset + 4], 'little', signed=True)
    assert disp == NAMES and i.disp_size == 4, hex(a)
    names.append((a, i.disp_offset, i.size))

ncls = {}
for b in bounds:
    ncls[b[4]] = ncls.get(b[4], 0) + 1
print('sites', len(sites), 'rip', sum(s[3] for s in sites), '| bounds', len(bounds), ncls, '| names', len(names))
assert len(sites) == 117 and len(bounds) == 112, 'counts changed'

hdr = f"""/* Generated by tools/dump-analysis (gen_tables.py) from a game.dll memory dump, build 25480438, and the reviewed
 * classification in docs/research/booster-table.md. Do not edit by hand. */
"""
with open(f'{OUT}/booster_sites.h', 'w') as f:
    f.write(hdr)
    f.write("/* Every instruction encoding a BoosterSettings address (game + 0x32FDA90, 21 rows of 56 bytes): {instruction rva,\n"
            " * displacement offset in it, instruction size, rip-relative (else image base + disp32), table offset}. */\n")
    f.write("static const BoosterSite kBoosterSites[] = {\n")
    for a, at, sz, rip, off in sites:
        f.write(f"    {{0x{a:07X}, {at}, {sz}, {rip}, 0x{off:03X}}},\n")
    f.write("};\n\n/* The enum name list's readers (game + 0x21DD630, image base + disp32): {rva, displacement offset, size}. */\n")
    f.write("static const BoosterSite kBoosterNameReaders[] = {\n")
    for a, at, sz in names:
        f.write(f"    {{0x{a:07X}, {at}, {sz}, 0, 0}},\n")
    f.write("};\n")
with open(f'{OUT}/booster_bounds.h', 'w') as f:
    f.write(hdr)
    f.write("/* Booster bounds and sentinels, each raised by the number of new boosters: {instruction rva, offset of the count\n"
            " * in it, its width in bytes, reviewed value (21, or 19 for idx-1)}. Guards, loop ends, sentinels (21 = none /\n"
            " * not found / rejected) and the picker cursor's clamp. */\n")
    f.write("static const BoosterBound kBoosterBounds[] = {\n")
    for a, at, w, v, c in bounds:
        f.write(f"    {{0x{a:07X}, {at}, {w}, {v}}}, /* {c.lower()} */\n")
    f.write("};\n")
